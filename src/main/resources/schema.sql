    temp_min_snap      DECIMAL(5,2) NOT NULL,
    temp_max_snap      DECIMAL(5,2) NOT NULL,
    tolerate_minutes   INT          NOT NULL,
    jitter_gap_minutes INT          NOT NULL,
    start_time         TIMESTAMP    NOT NULL,          -- 连续超限起点（合并抖动后）
    trigger_time       TIMESTAMP    NOT NULL,          -- 达到容忍时长、产生预警的采样点时间
    last_exceed_time   TIMESTAMP    NOT NULL,          -- 最近越限采样点时间
    duration_minutes   BIGINT       NOT NULL,          -- 触发时连续超限持续分钟
    peak_temperature   DECIMAL(5,2),                   -- 连续段内峰值（最偏离）温度
    description        VARCHAR(500) NOT NULL,
    source_category_no VARCHAR(32),                    -- 阈值来源类别（继承时为上级类别）
    -- OPEN 待处理 / RESOLVED 已处理；闭环只追加下列 resolve* 字段
    status             VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    resolve_note       VARCHAR(500),
    resolve_by         BIGINT,
    resolve_time       TIMESTAMP,
    create_by          BIGINT,
    create_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by          BIGINT,
    update_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 一条连续超限（按 批次×温区×起点）至多一条预警，数据库层兜底重启/并发重复扫描
    CONSTRAINT uk_cc_alert_open UNIQUE (batch_id, zone_code, start_time)
);
CREATE INDEX IF NOT EXISTS idx_cc_alert_batch ON t_cc_temp_alert (batch_id, id);
CREATE INDEX IF NOT EXISTS idx_cc_alert_status ON t_cc_temp_alert (status, trigger_time);

