-- 连续超限计时状态（按“批次×探头=采样点”；评估过程状态，重扫据此幂等，不删任何温度/预警事实）
CREATE TABLE IF NOT EXISTS t_cc_alert_streak (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id          BIGINT       NOT NULL,
    probe_id          BIGINT,                           -- 采样点（发运时固化在批次上的探头；无探头为空）
    zone_code         VARCHAR(32)  NOT NULL,
    -- 连续超限起点（抖动合并后不断开，保持首个越限采样点时间）
    streak_start_time TIMESTAMP    NOT NULL,
    -- 最近一个越限采样点时间
    last_exceed_time  TIMESTAMP    NOT NULL,
    -- 最近一个采样点时间（无论正常/越限），用于判断正常间隔是否落在抖动合并窗内
    last_sample_time  TIMESTAMP    NOT NULL,
    exceed_count      INT          NOT NULL DEFAULT 0, -- 连续段内越限采样点数
    -- 该连续段已产生的预警ID（产生后置位；重扫据此不再开第二条，空=尚未达到容忍时长）
    alert_id          BIGINT,
    -- ACTIVE 连续超限中（含抖动合并）/ BROKEN 已被超过合并窗的正常段断开
    status            VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by         BIGINT,
    create_time       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by         BIGINT,
    update_time       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_streak_point UNIQUE (batch_id, zone_code)
);

-- 温控预警（只追加：一次连续超限一条；闭环只追加 resolve*，绝不因模板变更消失）
