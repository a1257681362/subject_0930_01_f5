-- ============================================================================
-- 路线温区分段（V2 / cold-chain-2）
-- 设计要点：
-- 1. 一条运输路线一个主档（t_cc_route），按“季节”维护各自的版本序列；
--    版本只追加（t_cc_route_version），状态 DRAFT / EFFECTIVE / SUPERSEDED / REVOKED。
-- 2. 每个版本由若干相邻温区分段组成（t_cc_route_segment）：分段按里程 [from_km, to_km)
--    首尾相接覆盖 0 ~ total_km，既不能有空档也不能重叠；每段指定允许温区、缓冲时长（分钟）
--    与责任人。分段行随版本只追加，历史版本行永不修改——已派车批次按快照核对。
-- 3. 派车只登记路线；发运（批次开始执行）瞬间按“当前季节 + 当前时间”选取生效版本，把其全部分段
--    逐段复制为批次快照（t_cc_route_segment_snap）；派车后发运前发布的新版本仍作用于该批，
--    发运后版本热替换/撤回与在途批次无关。
-- 4. 发布是热替换：新草稿发布时把同季节当前生效版本置 SUPERSEDED；新版本只影响此后派车的
--    未发运批次，已经执行（已派车/在途/签收）的批次继续引用派车时的原快照。
-- 5. 撤回只能撤销“尚未生效”的版本（DRAFT，或已到生效时间窗但从未被批次引用的版本）；
--    已被任一批次引用固化快照的版本不可撤回。
-- 6. 发布前必须展示与当前生效版本的分段差异（ADDED/REMOVED/MODIFIED/UNCHANGED）。
-- ============================================================================

CREATE SEQUENCE IF NOT EXISTS seq_cc_route_no START WITH 30000001 INCREMENT BY 1;

-- 运输路线主档（一条路线一行；同一季节的版本挂在同一 route_id 下）
CREATE TABLE IF NOT EXISTS t_cc_route (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_no     VARCHAR(32)  NOT NULL,                -- 路线编号，序列生成，稳定唯一
    route_name   VARCHAR(128) NOT NULL,                -- 路线名称（如 上海中心仓-杭州一院）
    origin       VARCHAR(128),                         -- 起点
    destination  VARCHAR(128),                         -- 终点
    total_km     DECIMAL(8,2) NOT NULL,                -- 路线总里程，分段必须连续覆盖到该值
    status       VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / REVOKED
    remark       VARCHAR(255),
    create_by    BIGINT,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_route_no UNIQUE (route_no)
);

-- 路线季节版本（按季节各成版本序列；版本行只追加，状态机见类注释）
CREATE TABLE IF NOT EXISTS t_cc_route_version (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id       BIGINT       NOT NULL,
    season         VARCHAR(16)  NOT NULL,              -- SPRING/SUMMER/AUTUMN/WINTER/GENERAL
    version_no     INT          NOT NULL,              -- 同路线同季节内从 1 递增
    effective_from TIMESTAMP,                          -- 生效起点（可晚于发布时间=预约生效）
    effective_to   TIMESTAMP,                          -- 生效终点（空表示长期有效）
    publish_time   TIMESTAMP,                          -- 实际发布时间（DRAFT 时为空）
    change_reason  VARCHAR(255),
    status         VARCHAR(16)  NOT NULL DEFAULT 'DRAFT', -- DRAFT/EFFECTIVE/SUPERSEDED/REVOKED
    create_by      BIGINT,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_route_ver UNIQUE (route_id, season, version_no)
);
CREATE INDEX IF NOT EXISTS idx_cc_route_ver_pick ON t_cc_route_version (route_id, season, status);

-- 路线温区分段（属于某个季节版本；随版本只追加，永不修改/删除）
CREATE TABLE IF NOT EXISTS t_cc_route_segment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id      BIGINT       NOT NULL,
    segment_seq     INT          NOT NULL,             -- 段序号，从 1 按里程递增
    from_km         DECIMAL(8,2) NOT NULL,             -- 段起点公里标（含）
    to_km           DECIMAL(8,2) NOT NULL,             -- 段终点公里标（不含），末段到 total_km
    temp_min        DECIMAL(5,2) NOT NULL,             -- 本段允许温度下限 ℃
    temp_max        DECIMAL(5,2) NOT NULL,             -- 本段允许温度上限 ℃
    buffer_minutes  INT          NOT NULL,             -- 越限缓冲时长（分钟）：连续越限超过它才开异常
    owner_name      VARCHAR(64)  NOT NULL,             -- 本段责任人
    owner_phone     VARCHAR(32),
    remark          VARCHAR(255),
    create_by       BIGINT,
    create_time     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cc_seg_km CHECK (from_km < to_km),
    CONSTRAINT ck_cc_seg_temp CHECK (temp_min <= temp_max),
    CONSTRAINT ck_cc_seg_buffer CHECK (buffer_minutes >= 0)
);
CREATE INDEX IF NOT EXISTS idx_cc_seg_version ON t_cc_route_segment (version_id, segment_seq);

-- 批次路线分段快照（派车时从选定版本逐段固化；批次温度判定/追溯一律以快照为准）
CREATE TABLE IF NOT EXISTS t_cc_route_segment_snap (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT       NOT NULL,
    segment_seq     INT          NOT NULL,
    from_km         DECIMAL(8,2) NOT NULL,
    to_km           DECIMAL(8,2) NOT NULL,
    temp_min        DECIMAL(5,2) NOT NULL,
    temp_max        DECIMAL(5,2) NOT NULL,
    buffer_minutes  INT          NOT NULL,
    owner_name      VARCHAR(64)  NOT NULL,
    owner_phone     VARCHAR(32),
    remark          VARCHAR(255),
    create_by       BIGINT,
    create_time     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cc_segsnap_batch ON t_cc_route_segment_snap (batch_id, segment_seq);

-- 运输批次补充“路线引用”：派车登记路线、发运时选定路线季节版本并固化全部分段快照
